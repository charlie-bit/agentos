/**
 * Workflow composer: a draft -> YAML serializer, kept pure so the generated
 * file is testable without a DOM. The output must pass the real loader
 * (packages/contracts/src/workflow.ts) — this module only emits the closed
 * five-step union and the closed three-trigger union, never a new shape.
 *
 * Values are emitted as JSON-quoted scalars: valid YAML double-quoted flow
 * scalars, which keeps multi-line prompts and quotes safe without a YAML lib.
 */

export type StepDraft =
  | { type: "agent"; agent: string; prompt: string }
  | { type: "tool"; tool: string; args: string }
  | { type: "skill"; skill: string; prompt: string }
  | { type: "kb_search"; query: string }
  | { type: "review"; agent: string; prompt: string };

export type TriggerDraft = "manual" | "schedule" | "webhook";

export type InputSource = "none" | "manual";
export type OutputSink = "none" | "slack";

export interface WorkflowDraft {
  name: string;
  description: string;
  category: string;
  inputSource: InputSource;
  outputSink: OutputSink;
  outputChannel: string;
  trigger: TriggerDraft;
  cron: string;
  secretEnv: string;
  steps: StepDraft[];
}

const q = (s: string): string => JSON.stringify(s);

export function emptyDraft(): WorkflowDraft {
  return {
    name: "",
    description: "",
    category: "",
    inputSource: "manual",
    outputSink: "none",
    outputChannel: "",
    trigger: "manual",
    cron: "0 9 * * 1-5",
    secretEnv: "",
    steps: [{ type: "agent", agent: "", prompt: "" }],
  };
}

/** Human-readable problems; empty array = the draft would produce valid YAML. */
export function validateDraft(d: WorkflowDraft): string[] {
  const problems: string[] = [];
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(d.name.trim())) problems.push("name must be kebab-case (a-z, 0-9, single dashes)");
  if (d.steps.length === 0) problems.push("at least one step is required");
  if (d.trigger === "schedule" && d.cron.trim().split(/\s+/).length !== 5) problems.push("cron must have five fields");
  if (d.trigger === "webhook" && !/^[A-Za-z_][A-Za-z0-9_]*$/.test(d.secretEnv.trim())) problems.push("webhook secretEnv must be an env-var name");
  if (d.outputSink === "slack" && d.outputChannel.trim().length === 0) problems.push("slack output needs a channel id");
  d.steps.forEach((s, i) => {
    const at = `step ${i + 1}`;
    if (s.type === "agent" && (!s.agent.trim() || !s.prompt.trim())) problems.push(`${at}: agent and prompt are required`);
    if (s.type === "tool") {
      if (!s.tool.trim()) problems.push(`${at}: tool name is required`);
      if (s.args.trim().length > 0) {
        try {
          const parsed: unknown = JSON.parse(s.args);
          if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) problems.push(`${at}: args must be a JSON object`);
          else if (Object.values(parsed).some((v) => typeof v === "object" && v !== null)) problems.push(`${at}: args values must be string, number or boolean`);
        } catch {
          problems.push(`${at}: args is not valid JSON`);
        }
      }
    }
    if (s.type === "skill" && !s.skill.trim()) problems.push(`${at}: skill name is required`);
    if (s.type === "kb_search" && !s.query.trim()) problems.push(`${at}: query is required`);
    if (s.type === "review" && !s.agent.trim()) problems.push(`${at}: a reviewer role is required`);
  });
  return problems;
}

function stepLines(s: StepDraft): string[] {
  switch (s.type) {
    case "agent":
      return ["  - type: agent", `    agent: ${q(s.agent.trim())}`, `    prompt: ${q(s.prompt)}`];
    case "tool": {
      const lines = ["  - type: tool", `    tool: ${q(s.tool.trim())}`];
      if (s.args.trim().length > 0) {
        const parsed = JSON.parse(s.args) as Record<string, string | number | boolean>;
        const entries = Object.entries(parsed);
        if (entries.length > 0) {
          lines.push("    args:");
          for (const [k, v] of entries) lines.push(`      ${q(k)}: ${typeof v === "string" ? q(v) : String(v)}`);
        }
      }
      return lines;
    }
    case "skill":
      return [
        "  - type: skill",
        `    skill: ${q(s.skill.trim())}`,
        ...(s.prompt.trim().length > 0 ? [`    prompt: ${q(s.prompt)}`] : []),
      ];
    case "kb_search":
      return ["  - type: kb_search", `    query: ${q(s.query)}`];
    case "review":
      return [
        "  - type: review",
        `    agent: ${q(s.agent.trim())}`,
        ...(s.prompt.trim().length > 0 ? [`    prompt: ${q(s.prompt)}`] : []),
      ];
  }
}

/** Full manifest text. Call only after validateDraft() returned []. */
export function composeWorkflowYaml(d: WorkflowDraft): string {
  const lines = ["# Generated by the AgentOS workflow composer.", "kind: workflow", 'version: "1"', `name: ${q(d.name.trim())}`];
  if (d.description.trim().length > 0) lines.push(`description: ${q(d.description.trim())}`);
  if (d.category.trim().length > 0) lines.push(`category: ${q(d.category.trim())}`);
  lines.push("input:", `  source: ${d.inputSource}`);
  lines.push("output:");
  if (d.outputSink === "slack") lines.push("  sink: slack", `  channel: ${q(d.outputChannel.trim())}`);
  else lines.push("  sink: none");
  lines.push("trigger:", `  type: ${d.trigger}`);
  if (d.trigger === "schedule") lines.push(`  cron: ${q(d.cron.trim())}`);
  if (d.trigger === "webhook") lines.push(`  secretEnv: ${q(d.secretEnv.trim())}`);
  lines.push("steps:");
  for (const s of d.steps) lines.push(...stepLines(s));
  return lines.join("\n") + "\n";
}
